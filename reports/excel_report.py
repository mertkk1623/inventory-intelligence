def _title_block(
    sheet: Worksheet,
    title: str,
    context: ReportContext,
    *,
    last_col: int,
    subtitle: str = "",
) -> int:
    """Write the report banner and return the next free row."""

    product = context.product
    _merge(sheet, 1, last_col)
    banner = sheet.cell(row=1, column=1, value="INVENTORY INTELLIGENCE")
    banner.font = Font(name="Calibri", size=15, bold=True, color=TITLE_TEXT)
    banner.fill = PatternFill("solid", fgColor=NAVY)
    banner.alignment = Alignment(vertical="center", indent=1)
    sheet.row_dimensions[1].height = 30

    _merge(sheet, 2, last_col)
    heading = sheet.cell(row=2, column=1, value=title)
    heading.font = Font(name="Calibri", size=13, bold=True, color=NAVY)
    heading.fill = PatternFill("solid", fgColor="F2F5FA")
    heading.alignment = Alignment(vertical="center", indent=1)
    sheet.row_dimensions[2].height = 24

    _merge(sheet, 3, last_col)
    meta = sheet.cell(
        row=3,
        column=1,
        value=(
            f"{product.product_code} · {product.product_name} · "
            f"{context.unit} · Report date {fmt.day(context.report_date)} · "
            f"{context.report_type_label} · Generated {fmt.timestamp(context.generated_at)}"
        ),
    )
    meta.font = Font(name="Calibri", size=9, color=MUTED_TEXT)
    meta.alignment = Alignment(vertical="center", indent=1)
    sheet.row_dimensions[3].height = 18

    row = 4
    if subtitle:
        _merge(sheet, row, last_col)
        subtitle_cell = sheet.cell(row=row, column=1, value=subtitle)
        subtitle_cell.font = Font(name="Calibri", size=9, italic=True, color=MUTED_TEXT)
        subtitle_cell.alignment = Alignment(vertical="center", indent=1)
        row += 1

    return row + 1


def _section_row(sheet: Worksheet, row: int, label: str, *, last_col: int) -> int:
    _merge(sheet, row, last_col)
    cell = sheet.cell(row=row, column=1, value=label)
    cell.font = Font(name="Calibri", size=9, bold=True, color=NAVY)
    cell.fill = PatternFill("solid", fgColor=GROUP_FILL)
    cell.alignment = Alignment(vertical="center", indent=1)
    sheet.row_dimensions[row].height = 19
    return row + 1


def _header_row(
    sheet: Worksheet,
    row: int,
    labels: tuple[str, ...],
) -> int:
    for index, label in enumerate(labels, start=1):
        cell = sheet.cell(row=row, column=index, value=label or None)
        cell.font = Font(name="Calibri", size=10, bold=True, color=TITLE_TEXT)
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(vertical="center", indent=1)
        cell.border = Border(bottom=_THIN)
    sheet.row_dimensions[row].height = 21
    return row + 1


def _data_rows(
    sheet: Worksheet,
    row: int,
    rows: list[tuple],
    *,
    last_col: int,
) -> int:
    """Write label/value rows.

    Each entry is ``(label, value, unit, number_format)`` or
    ``(label, value, unit, detail, number_format)``. The five-element form
    fills an extra detail column, which is why the format is read positionally
    rather than assumed to be the fourth item.
    """

    for offset, entry in enumerate(rows):
        field, value, unit = entry[0], entry[1], entry[2]
        detail = entry[3] if len(entry) == 5 else ""
        number_format = entry[4] if len(entry) == 5 else entry[3]
        current = row + offset
        sheet.cell(row=current, column=1, value=field)
        value_cell = sheet.cell(row=current, column=2, value=value)
        if isinstance(number_format, str):
            value_cell.number_format = number_format
        sheet.cell(row=current, column=3, value=unit or "")
        if last_col >= 4:
            sheet.cell(row=current, column=4, value=detail or "")
        _style_row(sheet, current, last_col=last_col, zebra=offset % 2 == 1)
    return row + len(rows)


def _note_block(sheet: Worksheet, row: int, text: str, *, last_col: int) -> int:
    _merge(sheet, row, last_col)
    cell = sheet.cell(row=row, column=1, value=text)
    cell.font = Font(name="Calibri", size=9, color="334155")
    cell.fill = PatternFill("solid", fgColor="FFF8EA")
    cell.alignment = Alignment(wrap_text=True, vertical="top", indent=1)
    sheet.row_dimensions[row].height = max(18, 13 * (len(text) // 90 + 1))
    return row + 1


def _footer_block(
    sheet: Worksheet,
    row: int,
    context: ReportContext,
    *,
    last_col: int,
) -> None:
    _merge(sheet, row, last_col)
    cell = sheet.cell(
        row=row,
        column=1,
        value=(
            "Generated by Inventory Intelligence · Values come from the "
            f"validated workbook '{context.dataset.filename}' "
            f"({context.source_label}). Calculations use movements up to "
            f"{fmt.day(context.report_date)}."
        ),
    )
    cell.font = Font(name="Calibri", size=8.5, color=MUTED_TEXT)
    cell.alignment = Alignment(wrap_text=True, vertical="top", indent=1)


def _style_row(
    sheet: Worksheet,
    row: int,
    *,
    last_col: int,
    zebra: bool,
    fonts: dict[int, Font] | None = None,
) -> None:
    overrides = fonts or {}
    for column in range(1, last_col + 1):
        cell = sheet.cell(row=row, column=column)
        cell.font = overrides.get(column) or Font(
            name="Calibri", size=10, color=BODY_TEXT
        )
        cell.border = Border(bottom=_THIN)
        cell.alignment = Alignment(
            vertical="center",
            indent=1,
            horizontal="right"
            if column == 2 and isinstance(cell.value, (int, float))
            else "left",
        )
        if zebra:
            cell.fill = PatternFill("solid", fgColor=ZEBRA)


def _merge(sheet: Worksheet, row: int, last_col: int) -> None:
    if last_col > 1:
        sheet.merge_cells(
            start_row=row, start_column=1, end_row=row, end_column=last_col
        )


def _set_widths(sheet: Worksheet, widths: tuple[int, ...]) -> None:
    for index, width in enumerate(widths, start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
