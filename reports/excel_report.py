def _build_summary_sheet(sheet: Worksheet, context: ReportContext) -> None:
    product = context.product
    calculation = context.calculation

    last_row = _title_block(
        sheet,
        "Executive Summary",
        context,
        last_col=3,
    )
    row = _section_row(sheet, last_row, "PRODUCT", last_col=3)
    row = _header_row(sheet, row, ("Field", "Value", "Unit"))

    rows: list[tuple[str, object, str, str | None]] = [
        ("Product Code", product.product_code, "", None),
        ("Product Name", product.product_name, "", None),
        ("Report Date", calculation.report_date, "", DATE_FORMAT),
        ("Opening Stock", int(product.opening_stock), product.unit, QUANTITY_FORMAT),
        ("Current Stock", calculation.current_stock, product.unit, QUANTITY_FORMAT),
        ("Total IN", calculation.total_in, product.unit, QUANTITY_FORMAT),
        ("Total OUT", calculation.total_out, product.unit, QUANTITY_FORMAT),
    ]
    row = _data_rows(sheet, row, rows, last_col=3)

    row = _section_row(sheet, row, "CONSUMPTION", last_col=3)
    row = _header_row(sheet, row, ("Field", "Value", "Unit"))
    rows = [
        (
            "Average Daily Consumption",
            float(calculation.average_daily_consumption),
            f"{product.unit}/day",
            RATE_FORMAT,
        ),
        (
            "Consumption Window (days)",
            calculation.consumption_coverage_days,
            "days",
            QUANTITY_FORMAT,
        ),
        (
            "Days of Supply",
            float(calculation.days_of_supply)
            if calculation.days_of_supply is not None
            else "Not applicable",
            "days" if calculation.days_of_supply is not None else "",
            DECIMAL_FORMAT if calculation.days_of_supply is not None else None,
        ),
    ]
    row = _data_rows(sheet, row, rows, last_col=3)

    row = _section_row(sheet, row, "REPLENISHMENT", last_col=3)
    row = _header_row(sheet, row, ("Field", "Value", "Unit"))
    supported = calculation.replenishment_supported
    rows = [
        ("Safety Stock", calculation.safety_stock, product.unit, QUANTITY_FORMAT),
        ("Reorder Point", float(calculation.reorder_point), product.unit, DECIMAL_FORMAT),
        (
            "Open Order Quantity",
            calculation.total_open_order_quantity if supported else "Not included",
            product.unit if supported else "",
            QUANTITY_FORMAT if supported else None,
        ),
        ("Inventory Position", calculation.inventory_position, product.unit, QUANTITY_FORMAT),
        ("Target Stock", float(calculation.target_stock), product.unit, DECIMAL_FORMAT),
        (
            "Suggested Order Quantity",
            calculation.suggested_order_quantity if supported else "Not generated",
            product.unit if supported else "",
            QUANTITY_FORMAT if supported else None,
        ),
        (
            "Reorder Required",
            "Not supported" if not supported else ("Yes" if calculation.reorder_required else "No"),
            "",
            None,
        ),
        (
            "Overdue Orders",
            calculation.overdue_order_count if supported else "Not evaluated",
            "",
            QUANTITY_FORMAT if supported else None,
        ),
    ]
    row = _data_rows(sheet, row, rows, last_col=3)

    if not supported and calculation.replenishment_note:
        row = _note_block(sheet, row + 1, calculation.replenishment_note, last_col=3)

    if calculation.negative_stock_warning:
        row = _note_block(
            sheet,
            row + 1,
            f"Negative stock warning: the running balance fell to "
            f"{calculation.lowest_stock_balance:,} {product.unit}. Balances are "
            "reported without clamping.",
            last_col=3,
        )

    _footer_block(sheet, row + 1, context, last_col=3)

    _set_widths(sheet, (34, 30, 14))
    sheet.sheet_view.showGridLines = False
    sheet.page_setup.orientation = "portrait"
    sheet.page_setup.fitToWidth = 1
    sheet.sheet_properties.pageSetUpPr.fitToPage = True


def _build_movements_sheet(sheet: Worksheet, context: ReportContext) -> None:
    last_row = _title_block(
        sheet,
        "Stock Movements",
        context,
        last_col=5,
        subtitle=(
            "Movements on or before the report date, oldest first. The balance "
            "column is the engine closing balance for each movement date."
        ),
    )
    header_row = _header_row(
        sheet,
        last_row + 1,
        ("Date", "Transaction Type", "Quantity", "Description", "Stock Balance"),
    )

    rows = context.movement_rows()
    row_start = header_row
    for offset, (day, transaction_type, quantity, description, balance) in enumerate(
        rows
    ):
        row = row_start + offset
        sheet.cell(row=row, column=1, value=day).number_format = DATE_FORMAT
        sheet.cell(row=row, column=2, value=transaction_type)
        sheet.cell(row=row, column=3, value=quantity).number_format = QUANTITY_FORMAT
        sheet.cell(row=row, column=4, value=description or "")
        balance_cell = sheet.cell(row=row, column=5, value=balance)
        balance_cell.number_format = QUANTITY_FORMAT
        type_font = Font(
            name="Calibri",
            size=10,
            bold=True,
            color="16A36A" if transaction_type == TRANSACTION_IN else "DC4444",
        )
        _style_row(
            sheet,
            row,
            last_col=5,
            zebra=offset % 2 == 1,
            fonts={2: type_font},
        )

    if rows:
        last_data_row = row_start + len(rows) - 1
    else:
        sheet.cell(
            row=row_start,
            column=1,
            value="No stock movements were recorded on or before the report date.",
        ).font = Font(name="Calibri", size=10, italic=True, color=MUTED_TEXT)
        sheet.merge_cells(
            start_row=row_start, start_column=1, end_row=row_start, end_column=5
        )
        last_data_row = row_start

    sheet.freeze_panes = f"A{row_start}"
    sheet.auto_filter.ref = f"A{header_row - 1}:E{last_data_row}"
    _set_widths(sheet, (14, 18, 12, 44, 16))
    sheet.sheet_view.showGridLines = False
    sheet.page_setup.orientation = "landscape"
    sheet.page_setup.fitToWidth = 1
    sheet.sheet_properties.pageSetUpPr.fitToPage = True
    sheet.print_title_rows = f"{header_row - 1}:{header_row - 1}"


def _build_consumption_sheet(sheet: Worksheet, context: ReportContext) -> None:
    summary = context.summary
    calculation = context.calculation
    product = context.product

    window = (
        f"{fmt.day(context.consumption_start)} to {fmt.day(context.consumption_end)}"
        if context.daily
        else "No consumption window"
    )
    last_row = _title_block(
        sheet,
        "Consumption Analysis",
        context,
        last_col=4,
        subtitle=f"Consumption window: {window}.",
    )

    row = _section_row(sheet, last_row, "SUMMARY", last_col=4)
    row = _header_row(sheet, row, ("Measure", "Value", "Unit", "Detail"))
    rows: list[tuple[str, object, str, str, str | None]] = [
        (
            "Average Daily Consumption",
            float(calculation.average_daily_consumption),
            f"{product.unit}/day",
            f"{calculation.consumption_coverage_days} calendar days covered",
            RATE_FORMAT,
        ),
        ("Total Consumption", summary.total, product.unit, window, QUANTITY_FORMAT),
        (
            "Highest Consumption Day",
            summary.highest_quantity,
            product.unit,
            fmt.day(summary.highest_day) if summary.highest_day else "No consumption",
            QUANTITY_FORMAT,
        ),
        (
            "Lowest Consumption Day",
            summary.lowest_quantity,
            product.unit,
            fmt.day(summary.lowest_day) if summary.lowest_day else "No consumption window",
            QUANTITY_FORMAT,
        ),
    ]
    row = _data_rows(sheet, row, rows, last_col=4)

    row = _section_row(sheet, row, "DAILY CONSUMPTION", last_col=4)
    row = _header_row(sheet, row, ("Date", "Consumption", "Unit"))
    daily_start = row
    if context.daily:
        for offset, entry in enumerate(context.daily):
            current = daily_start + offset
            sheet.cell(row=current, column=1, value=entry.day).number_format = DATE_FORMAT
            sheet.cell(
                row=current, column=2, value=entry.quantity
            ).number_format = QUANTITY_FORMAT
            sheet.cell(row=current, column=3, value=product.unit)
            _style_row(sheet, current, last_col=3, zebra=offset % 2 == 1)
        row = daily_start + len(context.daily)
    else:
        sheet.cell(row=daily_start, column=1, value="No consumption days available.")
        sheet.merge_cells(
            start_row=daily_start, start_column=1, end_row=daily_start, end_column=4
        )
        row = daily_start + 1

    row = _section_row(sheet, row, "WEEKLY CONSUMPTION", last_col=4)
    row = _header_row(sheet, row, ("Week Starting", "Consumption", "Unit"))
    weekly_start = row
    if context.weekly:
        for offset, entry in enumerate(context.weekly):
            current = weekly_start + offset
            sheet.cell(
                row=current, column=1, value=entry.week_start
            ).number_format = DATE_FORMAT
            sheet.cell(
                row=current, column=2, value=entry.quantity
            ).number_format = QUANTITY_FORMAT
            sheet.cell(row=current, column=3, value=product.unit)
            _style_row(sheet, current, last_col=3, zebra=offset % 2 == 1)
        row = weekly_start + len(context.weekly)
    else:
        sheet.cell(row=weekly_start, column=1, value="No weekly totals available.")
        sheet.merge_cells(
            start_row=weekly_start, start_column=1, end_row=weekly_start, end_column=4
        )
        row = weekly_start + 1

    if summary.total == 0:
        row = _note_block(
            sheet,
            row,
            "No OUT movements were recorded in the consumption window. Every day "
            "is reported as zero and the average daily consumption is zero.",
            last_col=4,
        )

    _footer_block(sheet, row + 1, context, last_col=4)
    _set_widths(sheet, (34, 18, 12, 34))
    sheet.sheet_view.showGridLines = False
    sheet.page_setup.orientation = "portrait"
    sheet.page_setup.fitToWidth = 1
    sheet.sheet_properties.pageSetUpPr.fitToPage = True


