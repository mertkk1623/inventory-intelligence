"""Excel report generation with openpyxl.

The workbook is a presentation layer only: every value is read from
:class:`reports.report_data.ReportContext`, which itself wraps the shared
calculation engine result. No cell contains a formula.
"""

from __future__ import annotations

from io import BytesIO

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

from core.inventory import TRANSACTION_IN
from reports import formatting as fmt
from reports.report_data import ReportContext

NAVY = "14243A"
PRIMARY = "2563EB"
BORDER = "DCE3EC"
ZEBRA = "F7F9FC"
GROUP_FILL = "EDF2F9"
TITLE_TEXT = "FFFFFF"
MUTED_TEXT = "64748B"
BODY_TEXT = "1F2937"

SHEET_SUMMARY = "Executive Summary"
SHEET_MOVEMENTS = "Stock Movements"
SHEET_CONSUMPTION = "Consumption Analysis"
SHEET_REPLENISHMENT = "Replenishment Plan"
SHEET_ORDERS = "Open Purchase Orders"

SHEET_ORDER = (
    SHEET_SUMMARY,
    SHEET_MOVEMENTS,
    SHEET_CONSUMPTION,
    SHEET_REPLENISHMENT,
    SHEET_ORDERS,
)

DATE_FORMAT = "yyyy-mm-dd"
QUANTITY_FORMAT = "#,##0"
DECIMAL_FORMAT = "#,##0.0"
RATE_FORMAT = "#,##0.00"

_THIN = Side(style="thin", color=BORDER)


def build_excel_report(context: ReportContext) -> bytes:
    """Build the complete Excel report in memory and return its bytes."""

    workbook = Workbook()
    summary_sheet = workbook.active
    summary_sheet.title = SHEET_SUMMARY

    _build_summary_sheet(summary_sheet, context)
    _build_movements_sheet(workbook.create_sheet(SHEET_MOVEMENTS), context)
    _build_consumption_sheet(workbook.create_sheet(SHEET_CONSUMPTION), context)
    _build_replenishment_sheet(workbook.create_sheet(SHEET_REPLENISHMENT), context)
    _build_orders_sheet(workbook.create_sheet(SHEET_ORDERS), context)

    workbook.properties.title = (
        f"Inventory Intelligence report · {context.product.product_code}"
    )
    workbook.properties.subject = f"Inventory report as of {context.report_date}"
    workbook.properties.creator = "Inventory Intelligence"
    workbook.properties.description = (
        "Generated by Inventory Intelligence from the validated workbook "
        f"'{context.dataset.filename}'."
    )

    buffer = BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


